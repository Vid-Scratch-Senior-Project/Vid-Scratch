def ftv_loss_from_window(video_small, clip_len=8, stride=4):
    T = video_small.shape[2]
    feats = []
    for t in range(0, T - clip_len + 1, stride):
        clip = video_small[:, :, t:t+clip_len]
        feat = feature_model(clip).flatten(1)
        feats.append(feat)
    if len(feats) < 2:
        return torch.tensor(0.0, device=device)
    feats = torch.cat(feats, 0)
    return ((feats[1:] - feats[:-1]) ** 2).mean()


# ---------------- Poison ONE window ----------------
def poison_window(frames):
    video = np.stack(frames).astype(np.float32) / 255.0
    video = torch.from_numpy(video).permute(3,0,1,2).unsqueeze(0).to(device)

    delta = torch.zeros_like(video, requires_grad=True)
    opt = torch.optim.Adam([delta], lr=LR)

    for step in range(STEPS):
        opt.zero_grad()

        poisoned = torch.clamp(video + delta, 0, 1)
        poisoned_small = resize_for_model(poisoned)

        ftv = ftv_loss_from_window(poisoned_small)
        pix = output_temporal_inconsistency(poisoned)

        loss = -(W_FTV * ftv + W_PIX * pix)
        loss.backward()
        opt.step()

        with torch.no_grad():
            delta.clamp_(-TARGET_EPS, TARGET_EPS)

        if step % 10 == 0:
            linf_now = delta.abs().max().item() * 255
            print(f"step {step:02d} | l_inf ≈ {linf_now:.2f}/255")

    with torch.no_grad():
        out = torch.clamp(video + delta, 0, 1)

    diff = (out - video).abs().max().item() * 255
    print(f"FINAL l_inf ≈ {diff:.2f}/255")

    out_np = out.squeeze(0).permute(1,2,3,0).cpu().numpy()
    return (out_np * 255).astype(np.uint8)


