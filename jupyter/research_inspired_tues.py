@torch.no_grad()
def feature_temporal_variance_stream(video_cthw, clip_len=8, stride=2):
    C, T, H, W = video_cthw.shape
    prev_feat = None
    sum_sq = 0.0
    count = 0

    for t in range(0, T - clip_len + 1, stride):
        clip = video_cthw[:, t:t+clip_len].unsqueeze(0).to(device)  # (1,C,T,H,W)
        clip_small = resize_for_model(clip)
        feat = feature_model(clip_small).flatten(1).cpu()

        if prev_feat is not None:
            diff = feat - prev_feat
            sum_sq += diff.pow(2).mean().item()
            count += 1

        prev_feat = feat

        del clip, clip_small, feat
        if device == "cuda":
            torch.cuda.empty_cache()

    return sum_sq / max(count, 1)

