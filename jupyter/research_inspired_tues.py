# ---------------- Temporal variance (pixel) ----------------
def temporal_variance_cthw(video_cthw):
    # video_cthw: (C,T,H,W) in [0,1]
    diffs = video_cthw[:, 1:] - video_cthw[:, :-1]
    return diffs.pow(2).mean().item()

# ---------------- Flicker term on OUTPUT (stronger than delta-only) ----------------
def output_temporal_inconsistency(poisoned):
    # poisoned: (N,C,T,H,W)
    diffs = poisoned[:, :, 1:] - poisoned[:, :, :-1]
    return torch.mean(diffs**2)

