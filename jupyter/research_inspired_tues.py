# ============================================================
# Feature Temporal Variance (FTV) loss inside a window
# - take multiple sub-clips across time
# - maximize feature changes across time
# ============================================================
def ftv_loss_from_window(poisoned_small, clip_len=8, stride=4):
    """
    poisoned_small: (1,3,T,112,112)
    Return: scalar loss that is HIGH when feature changes across time are high
    """
    T = poisoned_small.shape[2]
    feats = []
    for t in range(0, T - clip_len + 1, stride):
        sub = poisoned_small[:, :, t:t+clip_len]            # (1,3,clip_len,112,112)
        feat = feature_model(sub).flatten(1)                # (1,dim)
        feats.append(feat)

    if len(feats) < 2:
        return torch.tensor(0.0, device=poisoned_small.device)

    feats = torch.cat(feats, dim=0)                         # (K,dim)
    diffs = feats[1:] - feats[:-1]
    return torch.mean(diffs**2)                             # high = more temporal disruption

# ============================================================
# TUEs poisoning for ONE WINDOW ✅ STRONGER LOSS
# - maximize FTV (feature temporal disruption)
# - add pixel flicker on output
# - keep perturbation bounded
# ============================================================
def poison_window(frames,
                 steps=30,
                 eps=20/255,
                 lr=2e-3,
                 w_ftv=1.5,
                 w_pix=0.3,
                 clip_len=8,
                 clip_stride=4):
    """
    frames: list RGB uint8 length T
    returns: poisoned_chunk_uint8, metrics dict (pre-encode)
    """
    video = np.stack(frames).astype(np.float32) / 255.0                 # (T,H,W,3)
    video = torch.from_numpy(video).permute(3,0,1,2).unsqueeze(0).to(device)  # (1,3,T,H,W)

    delta = torch.zeros_like(video, requires_grad=True)
    opt = torch.optim.Adam([delta], lr=lr)

    for _ in range(steps):
        opt.zero_grad()

        poisoned = torch.clamp(video + delta, 0, 1)

        # model view (112) only for feature loss
        poisoned_small = resize_for_model(poisoned)

        # NEW: maximize feature temporal variance (FTV)
        ftv = ftv_loss_from_window(poisoned_small, clip_len=clip_len, stride=clip_stride)

        # also encourage visible flicker in pixel domain (but keep small weight)
        pix_flicker = output_temporal_inconsistency(poisoned)

        # minimize negative => maximize both
        loss = -(w_ftv * ftv + w_pix * pix_flicker)

        loss.backward()
        opt.step()

        with torch.no_grad():
            delta.clamp_(-eps, eps)

    with torch.no_grad():
        out = torch.clamp(video + delta, 0, 1)

    # ---- metrics BEFORE encode ----
    clean_tv = temporal_variance_cthw(video.squeeze(0).detach().cpu())
    pois_tv  = temporal_variance_cthw(out.squeeze(0).detach().cpu())
    ratio_tv = (pois_tv / clean_tv) if clean_tv > 0 else float("inf")

    diff = (out - video).detach()
    l_inf = diff.abs().max().item()
    l2 = (torch.norm(diff).item() / diff.numel())

    # convert to uint8 frames (keep original H,W)
    out_np = out.squeeze(0).permute(1,2,3,0).cpu().numpy()
    out_np = np.clip(out_np, 0, 1)
    out_u8 = (out_np * 255).astype(np.uint8)

    metrics = {
        "pixel_tv_clean": clean_tv,
        "pixel_tv_pois": pois_tv,
        "pixel_tv_ratio": ratio_tv,
        "l_inf": l_inf,
        "l2_norm_per_elem": l2
    }
    return out_u8, metrics

