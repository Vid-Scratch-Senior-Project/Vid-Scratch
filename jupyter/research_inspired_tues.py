def load_frames(video_path, max_frames=192):
    cap = cv2.VideoCapture(video_path)
    fps = cap.get(cv2.CAP_PROP_FPS) or 30.0
    frames = []
    while len(frames) < max_frames:
        ret, frame = cap.read()
        if not ret:
            break
        frames.append(cv2.cvtColor(frame, cv2.COLOR_BGR2RGB))
    cap.release()
    print("Loaded frames:", len(frames), "FPS:", fps)
    return frames, fps


def resize_for_model(video, size=112):
    n, c, t, h, w = video.shape
    x = video.permute(0,2,1,3,4).reshape(n*t, c, h, w)
    x = F.interpolate(x, size=(size, size), mode="bilinear", align_corners=False)
    x = x.reshape(n, t, c, size, size).permute(0,2,1,3,4)
    return x


def output_temporal_inconsistency(video):
    return ((video[:, :, 1:] - video[:, :, :-1]) ** 2).mean()


