# ---------------- Resize (spatial only) for model ----------------
def resize_for_model(video, size=112):
    # video: (N,C,T,H,W)
    n, c, t, h, w = video.shape
    video2 = video.permute(0,2,1,3,4).reshape(n*t, c, h, w)
